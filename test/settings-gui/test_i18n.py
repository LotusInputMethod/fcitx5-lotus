def _write_mo(path, catalog):
    """Serializes a catalog into a minimal GNU .mo file."""
    keys = sorted(catalog)
    ids = b"".join(key.encode() + b"\x00" for key in keys)
    strs = b"".join(catalog[key].encode() + b"\x00" for key in keys)
    count = len(keys)

    offsets = []
    id_offset = 0
    str_offset = 0
    for key in keys:
        key_bytes = key.encode()
        value_bytes = catalog[key].encode()
        offsets.append((id_offset, len(key_bytes), str_offset, len(value_bytes)))
        id_offset += len(key_bytes) + 1
        str_offset += len(value_bytes) + 1

    keystart = 28 + 16 * count  # past the key and value index tables
    valuestart = keystart + len(ids)
    key_offsets = []
    value_offsets = []
    for o1, l1, o2, l2 in offsets:
        key_offsets += [l1, o1 + keystart]
        value_offsets += [l2, o2 + valuestart]

    output = struct.pack("<Iiiiiii", 0x950412DE, 0, count, 28, 28 + 8 * count, 0, 0)
    output += struct.pack(f"<{4 * count}i", *(key_offsets + value_offsets))
    output += ids + strs
    with open(path, "wb") as handle:
        handle.write(output)


class NGettextTests(unittest.TestCase):
    def test_module_gettext_is_standard_gettext(self):
        self.assertIs(i18n._, gettext.gettext)


class SetupI18nTests(unittest.TestCase):
    def setUp(self):
        self._original_locale_dir = i18n.LOCALE_DIR
        self._tmp = tempfile.TemporaryDirectory()
        self.localedir = os.path.join(self._tmp.name, "locale")

    def tearDown(self):
        i18n.LOCALE_DIR = self._original_locale_dir
        self._tmp.cleanup()

    def _install_vietnamese_catalog(self):
        messages_dir = os.path.join(self.localedir, "vi", "LC_MESSAGES")
        os.makedirs(messages_dir)
        _write_mo(
            os.path.join(messages_dir, "fcitx5-lotus.mo"),
            {
                "": "Content-Type: text/plain; charset=UTF-8\n",
                "Add": "Th\u00eam",
                "Remove": "X\u00f3a",
            },
        )

    def test_binds_domain_when_locale_dir_exists(self):
        self._install_vietnamese_catalog()
        i18n.LOCALE_DIR = self.localedir

        # Spy on the gettext binding calls: the catalog assertions below only
        # work if setup_i18n actually registered domain and locale dir.
        with (
            mock.patch("gettext.bindtextdomain") as fake_bind,
            mock.patch("gettext.textdomain") as fake_textdomain,
        ):
            i18n.setup_i18n()

        fake_bind.assert_called_once_with("fcitx5-lotus", self.localedir)
        fake_textdomain.assert_called_once_with("fcitx5-lotus")
        translation = gettext.translation("fcitx5-lotus", self.localedir, languages=["vi"])
        self.assertEqual(translation.gettext("Add"), "Th\u00eam")

    def test_missing_locale_dir_does_not_raise(self):
        i18n.LOCALE_DIR = os.path.join(self.localedir, "does-not-exist")

        # The os.path.exists guard must skip binding for a missing locale dir.
        with mock.patch("gettext.bindtextdomain") as fake_bind:
            i18n.setup_i18n()

        fake_bind.assert_not_called()

    def test_locale_errors_are_swallowed(self):
        original_setlocale = locale.setlocale

        def _raise(*args, **kwargs):
            raise RuntimeError("broken locale")

        locale.setlocale = _raise
        try:
            with redirect_stdout(StringIO()) as captured:
                i18n.setup_i18n()
        finally:
            locale.setlocale = original_setlocale

        self.assertIn("Failed to initialize i18n", captured.getvalue())


class LocaleDirFallbackTests(unittest.TestCase):
    def test_default_locale_dir_without_generated_paths_module(self):
        # paths.py is generated by CMake into the build tree; in the source
        # tree i18n falls back to the system locale directory.
        self.assertEqual(i18n.LOCALE_DIR, "/usr/share/locale")


